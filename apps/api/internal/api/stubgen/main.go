// Command stubgen writes unimplemented.gen.go: an Unimplemented type with one method per
// operation in StrictServerInterface, each returning ErrNotImplemented. Handlers embed it,
// so a new operation in the contract compiles at once and answers 501 until it is built.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
)

const (
	source = "api.gen.go"
	target = "unimplemented.gen.go"
)

func main() {
	if err := run(); err != nil {
		log.Fatal(err)
	}
}

func run() error {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, source, nil, parser.SkipObjectResolution)
	if err != nil {
		return fmt.Errorf("parse %s: %w", source, err)
	}
	methods, err := strictMethods(file)
	if err != nil {
		return err
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by stubgen from StrictServerInterface. DO NOT EDIT.\n\n")
	b.WriteString("package api\n\nimport \"context\"\n\n")
	b.WriteString("// Unimplemented answers every operation with ErrNotImplemented. Embed it in the\n")
	b.WriteString("// handler set and override operations as their domain is built.\n")
	b.WriteString("type Unimplemented struct{}\n\n")
	b.WriteString("var _ StrictServerInterface = Unimplemented{}\n")
	for _, m := range methods {
		fmt.Fprintf(&b, "\n// %s is not implemented yet.\n", m.name)
		fmt.Fprintf(&b, "func (Unimplemented) %s(context.Context, %s) (%s, error) {\n\treturn nil, ErrNotImplemented\n}\n",
			m.name, m.request, m.response)
	}

	out, err := format.Source(b.Bytes())
	if err != nil {
		return fmt.Errorf("format: %w", err)
	}
	return os.WriteFile(target, out, 0o600)
}

type method struct{ name, request, response string }

func strictMethods(file *ast.File) ([]method, error) {
	for _, decl := range file.Decls {
		gen, ok := decl.(*ast.GenDecl)
		if !ok || gen.Tok != token.TYPE {
			continue
		}
		for _, spec := range gen.Specs {
			ts, ok := spec.(*ast.TypeSpec)
			if !ok || ts.Name.Name != "StrictServerInterface" {
				continue
			}
			iface, ok := ts.Type.(*ast.InterfaceType)
			if !ok {
				return nil, fmt.Errorf("StrictServerInterface is not an interface")
			}
			var out []method
			for _, f := range iface.Methods.List {
				fn, ok := f.Type.(*ast.FuncType)
				if !ok || len(f.Names) != 1 || len(fn.Params.List) != 2 || len(fn.Results.List) != 2 {
					return nil, fmt.Errorf("unexpected method shape in StrictServerInterface")
				}
				req, okReq := fn.Params.List[1].Type.(*ast.Ident)
				res, okRes := fn.Results.List[0].Type.(*ast.Ident)
				if !okReq || !okRes {
					return nil, fmt.Errorf("unexpected types on %s", f.Names[0].Name)
				}
				out = append(out, method{name: f.Names[0].Name, request: req.Name, response: res.Name})
			}
			return out, nil
		}
	}
	return nil, fmt.Errorf("StrictServerInterface not found in %s", source)
}
