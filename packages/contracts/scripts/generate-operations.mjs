// Writes src/operations.gen.ts: operation ID → HTTP method, path template, auth
// and the headers the transport must add. The http client routes repository
// calls with it. Run through `pnpm generate`; CI checks the output is current.
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const METHODS = ['get', 'put', 'post', 'patch', 'delete'];
const dir = mkdtempSync(join(tmpdir(), 'nem-contracts-'));
const bundled = join(dir, 'openapi.json');

try {
  // Redocly resolves every $ref, so parameters can be read by header name.
  execFileSync(
    'redocly',
    ['bundle', 'openapi.yaml', '--dereferenced', '--ext', 'json', '-o', bundled],
    {
      stdio: 'ignore',
      shell: true,
    },
  );
  const spec = JSON.parse(readFileSync(bundled, 'utf8'));

  const authOf = (security) => {
    const schemes = (security ?? spec.security ?? []).flatMap(Object.keys);
    if (schemes.length === 0) return 'none';
    if (schemes.includes('bearerAuth')) return 'bearer';
    if (schemes.includes('staffAuth')) return 'staff';
    return 'apiKey';
  };

  const rows = [];
  for (const [path, item] of Object.entries(spec.paths)) {
    for (const method of METHODS) {
      const op = item[method];
      if (!op) continue;
      const headers = new Set(
        [...(item.parameters ?? []), ...(op.parameters ?? [])]
          .filter((p) => p.in === 'header')
          .map((p) => p.name),
      );
      rows.push({
        id: op.operationId,
        method: method.toUpperCase(),
        path,
        auth: authOf(op.security),
        idempotent: headers.has('Idempotency-Key'),
        signed: headers.has('X-Device-Signature'),
      });
    }
  }
  rows.sort((a, b) => a.id.localeCompare(b.id));
  // Outbound developer events share the operations type but are not routes.
  const webhookIds = Object.values(spec.webhooks ?? {})
    .flatMap((item) => METHODS.map((m) => item[m]?.operationId))
    .filter(Boolean)
    .sort();

  const body = rows
    .map(
      (r) =>
        `  ${r.id}: { method: '${r.method}', path: '${r.path}', auth: '${r.auth}', idempotent: ${r.idempotent}, signed: ${r.signed} },`,
    )
    .join('\n');

  writeFileSync(
    'src/operations.gen.ts',
    `// Generated by scripts/generate-operations.mjs from openapi.yaml. Do not edit.
import type { operations } from './schema.gen';

export type HttpMethod = 'GET' | 'PUT' | 'POST' | 'PATCH' | 'DELETE';
/** \`none\` is public; \`bearer\` is a customer session; staff and API keys are console/developer only. */
export type OperationAuth = 'none' | 'bearer' | 'staff' | 'apiKey';

export interface OperationMeta {
  method: HttpMethod;
  /** Path template, e.g. \`/v1/transfers/{transfer_id}\`. */
  path: string;
  auth: OperationAuth;
  /** Takes an \`Idempotency-Key\` header. */
  idempotent: boolean;
  /** Needs a device signature (\`X-Device-*\`, \`X-Signature-Timestamp\`, \`X-Nonce\`). */
  signed: boolean;
}

/** Operation IDs of outbound webhooks: described in the contract, never called. */
export type WebhookOperationId = ${webhookIds.map((id) => `'${id}'`).join(' | ') || 'never'};
/** Every operation the API serves. */
export type RouteOperationId = Exclude<keyof operations, WebhookOperationId>;

export const OPERATIONS = {
${body}
} as const satisfies Record<RouteOperationId, OperationMeta>;
`,
  );
  console.log(`operations.gen.ts: ${rows.length} operations`);
} finally {
  rmSync(dir, { recursive: true, force: true });
}
